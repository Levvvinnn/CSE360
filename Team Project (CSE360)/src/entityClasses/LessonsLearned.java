package entityClasses;

import java.sql.Timestamp;

/*******
 * <p> Title: LessonLearned Class </p>
 * 
 * <p> Description: This entity class represents one lesson learned in the system.  It holds the
 * "core information" a contributor enters (title, description, category) and the values the
 * system generates (id, author, created and updated timestamps).  It follows the same pattern as
 * the User entity class: private attributes, a constructor, getters, and a few setters. </p>
 * 
 * <p> Design note: the text setters remove leading and trailing spaces.  Doing it here, in one
 * place, means the validator and the database always see the same cleaned value, so a title of
 * only spaces is treated as empty everywhere. </p>
 * 
 * <p> Copyright: Lynn Robert Carter © 2025 </p>
 * 
 * @author Lynn Robert Carter
 * 
 * @version 1.00		2026-10-05 Initial version for HW2
 */
public class LessonsLearned {
	
	/*
	 * These are the private attributes for this entity object
	 */
	private int id;						// Generated by the database; -1 until the lesson is saved
	private String title;
	private String description;
	private String category;
	private String author;				// The username of the contributor who added the lesson
	private Timestamp createdAt;
	private Timestamp updatedAt;
	
	/*****
	 * <p> Method: LessonLearned(String author, String title, String description,
	 * 		String category) </p>
	 * 
	 * <p> Description: This constructor is used for a new lesson that has not yet been saved.
	 * The id and timestamps are filled in later by the database. </p>
	 * 
	 * @param author specifies the username of the contributor adding the lesson
	 * 
	 * @param title specifies the title of the lesson
	 * 
	 * @param description specifies the description of the lesson
	 * 
	 * @param category specifies the category of the lesson
	 */
	public LessonsLearned(String author, String title, String description, String category) {
		this.id = -1;
		this.author = author;
		setTitle(title);
		setDescription(description);
		setCategory(category);
	}
	
	/*****
	 * <p> Method: LessonLearned(int id, String author, String title, String description,
	 * 		String category, Timestamp createdAt, Timestamp updatedAt) </p>
	 * 
	 * <p> Description: This constructor is used when a lesson is read back from the database. </p>
	 * 
	 * @param id the database id of the lesson
	 * 
	 * @param author the username of the contributor who added the lesson
	 * 
	 * @param title the title of the lesson
	 * 
	 * @param description the description of the lesson
	 * 
	 * @param category the category of the lesson
	 * 
	 * @param createdAt the time the lesson was added
	 * 
	 * @param updatedAt the time the lesson was last changed
	 */
	public LessonsLearned(int id, String author, String title, String description,
			String category, Timestamp createdAt, Timestamp updatedAt) {
		this(author, title, description, category);
		this.id = id;
		this.createdAt = createdAt;
		this.updatedAt = updatedAt;
	}
	
	// Private helper: null becomes an empty string and spaces at the ends are removed
	private static String clean(String s) {
		return (s == null) ? "" : s.trim();
	}
	
	/*****
	 * <p> Method: int getId() </p>
	 * @return the database id, or -1 if the lesson has not been saved
	 */
	public int getId() { return id; }
	
	/*****
	 * <p> Method: String getTitle() </p>
	 * @return the title
	 */
	public String getTitle() { return title; }
	
	/*****
	 * <p> Method: String getDescription() </p>
	 * @return the description
	 */
	public String getDescription() { return description; }
	
	/*****
	 * <p> Method: String getCategory() </p>
	 * @return the category
	 */
	public String getCategory() { return category; }
	
	/*****
	 * <p> Method: String getAuthor() </p>
	 * @return the username of the contributor who added the lesson
	 */
	public String getAuthor() { return author; }
	
	/*****
	 * <p> Method: Timestamp getCreatedAt() </p>
	 * @return the time the lesson was added
	 */
	public Timestamp getCreatedAt() { return createdAt; }
	
	/*****
	 * <p> Method: Timestamp getUpdatedAt() </p>
	 * @return the time the lesson was last changed
	 */
	public Timestamp getUpdatedAt() { return updatedAt; }
	
	/*****
	 * <p> Method: void setTitle(String s) </p>
	 * @param s the new title (spaces at the ends are removed)
	 */
	public void setTitle(String s) { title = clean(s); }
	
	/*****
	 * <p> Method: void setDescription(String s) </p>
	 * @param s the new description (spaces at the ends are removed)
	 */
	public void setDescription(String s) { description = clean(s); }
	
	/*****
	 * <p> Method: void setCategory(String s) </p>
	 * @param s the new category (spaces at the ends are removed)
	 */
	public void setCategory(String s) { category = clean(s); }
}
